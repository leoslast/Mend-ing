            <p>The world is mostly composed of three parts, &quot;Above&quot;, earth and the underground.
                <br>&quot;Above&quot; is where all angels live, they can enter once they turn 18 since that&#39;s when they&#39;ll have to start their tasks. No one beside angels can enter here, and even if someone managed to enter theres guards who control the access.
                <br>Earth is where everything happens, all lifeforms can exist and freely roam this place (as long as they do not commit crime). Theres police who regulate people with the aid of the angels in the worst cases.
                <br>The Underground is a place that only demons can enter, yet most of them avoid that place since no one rules over there. It&#39;s said that only those who are truly corrupt live there, always trying to catch demons dumb enough to go down. It is extremly hard to get in, and even harder to escape. It hasn&#39;t been documented how demons leave the place, since most of them are ashamed of even being there so they avoid saying they were even there.</p>

            <p>One of the main forms of entertainment and ways of making money is by fighting. Tournaments are hosted basically every other day, some for fun, others for money. Fame is something that can bring many luxuries to your life. Still, this isn&#39;t to say you can&#39;t live by other means, since theres still people who need to manage this cases and just regular stores.</p>

            <p>The class system has a ranking, meaning that those who are part of the higher classes have more power naturally. However this isn&#39;t to say that those who are from lower classes are weak, since training can change everything here. Basically, your class just gives you a head start. Most people don&#39;t care about classes since they just see it as an extra of how to look, only prestigious families are worried about those stuff.</p>

            <p>Classes by ranking and a description</p>

            <p>1. Fallen angels:</p>
            <div class="fr-spoiler">

                <p>One can not be born as a fallen angel, the only way to become one is by, of course, being an angel first. If the &quot;Supreme Angel&quot; decides you are not doing a good job at being a role model as angels should be, you&#39;ll become a fallen angel. Once you fall, you&#39;re sent immediately sent to the underground where you&#39;re on your own at that point. Most of those who fall don&#39;t make it out to Earth again.</p>

                <p>Despite being stronger, those who belong to this class are heavily criticized by society, since they failed their mission as angels and/or where corrupted by evil.</p>

                <p>The physical trait they have is that their original halo will be tainted by a new color and breaking, they&#39;ll gain horns, and their old wings will change color as well. It&#39;s not possible to hide these traits.</p>
            </div>

            <p>2. Vessel:</p>
            <div class="fr-spoiler">

                <p>Those who belong to this class will have an extremely delicate body which behaves like ceramics, breaking when being attacked. Technology isn&#39;t developed enough to the point of being able to hide the cracks, but enough to avoid deaths when a vessel becomes too damaged.&nbsp;</p>

                <p>This is a rare class, not many vessels are born and even less are alive nowadays since it&#39;s very hard to maintain a happy life in a combat focused world when if you get wounded you break. Those vessels who decide to pursue the fighting life are forced to retire very early into their careers because of their body, yet in their active time they tend to become very famous since their higher ranking. (And the morbid curiosity of people wondering &quot;Will this be their last fight? Will we get to see them break into pieces today?&quot;).</p>
            </div>

            <p>3. Moon:</p>
            <div class="fr-spoiler">

                <p>As the name says, those who belong to this class will have a moon in a place of their body. It can be between their collar bones, on their backs, above their heads, etc.</p>

                <p>The moon can be at any phase, there hasn&#39;t been any reports if this affects in any way the person, be it a possitive or negative way. A person can have up to three moons on their body. It can&#39;t be touched.</p>

                <p>It&#39;s not possible to hide this trait.</p>
            </div>

            <p>4. Eye:</p>
            <div class="fr-spoiler">

                <p>Those who belong to this group have an extra eye on their body. It&#39;ll take time for the person to be able to control the eye and see through it, though it doesn&#39;t always appear in a convenient zone, therefore some never develope this ability.</p>

                <p>Society tends to judge those who use their extra eye outside of combat. Some would say it&#39;s because of envy, others will say it gives them weird vibes.</p>

                <p>This trait can be hidden.</p>
            </div>

            <p>5. Angel:</p>
            <div class="fr-spoiler">

                <p>Despite not being one of the higher classes in the ranking, it&#39;s pretty rare for an angel to be born. It is considered an honor to be part of this class, since angels carry the duty of keeping the balance of the world in check and making sure nothing extreme happens on earth. Most angels decide to live &quot;Above&quot; so they&#39;re ready if the &quot;Supreme Angel&quot; might suddenly call them, yet they can still live on earth.
                    <br>One of their duties as angels is giving support to the police of the world if a case becomes too hard for them.&nbsp;</p>

                <p>An angel can report to the &quot;Supreme Angel&quot; if another angel is breaking the rules or are slacking with their jobs. It&#39;s not bad looked, yet it can bring a lot of trouble if they decide to wrongly accuse somebody.</p>

                <p>Their physical traits are a halo and wings. They can have multiple of those, and when powers are activated the halos can split into two. The halo must not have any edges.
                    <br>Every angel is born with the power of summoning a Blessed Lance (name subject to change), meaning that most angels actually have two powers.</p>

                <p>It&#39;s not possible to hide these traits.</p>
            </div>

            <p>6. Demons:</p>
            <div class="fr-spoiler">

                <p>Everyone who is a demon must have a tail and an horns. Some demons are born with wings and even more tails, yet it isn&#39;t very common.
                    <br>Horns are a tricky trait, since they can appear in the head or limbs. There was a rare case where the horn appeared in the back, but it isn&#39;t common at all. Most demons have two horns, yet it&#39;s not a fixed number. These can break and it&#39;ll slowly regenerate, but it&#39;s a painful process that most demons avoid.</p>

                <p>Between demons, they consider those who have wings of more power, yet it&#39;s seen as bad to have more than one tail. (Why? Who knows, demons have their own society apparently.)</p>

                <p>It&#39;s not possible to hide these traits.</p>
            </div>

            <p>7. Heart:</p>
            <div class="fr-spoiler">

                <p>Those who belong to this group have a heart on their body. It can be a full heart, broken in two or just one half. It isn&#39;t known if when you have one half it&#39;s possible to find your &quot;other half&quot;.</p>

                <p>The heart can appear upside down, and in cases where its broken in two, it isn&#39;t necessary for the half&#39;s to have the same orientation. The heart can appear anywhere on the body and it can&#39;t be touched (Despite some people say to be more sensitive in these places, it isn&#39;t confirmed).</p>

                <p>It&#39;s not possible to hide this trait.</p>
            </div>

